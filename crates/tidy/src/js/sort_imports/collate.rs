/// A collation element's primary weight.
#[derive(Copy, Clone, PartialEq, Eq, PartialOrd, Ord)]
enum Primary<'t> {
  Symbol(u32),
  /// With numeric collation, a run of digits without its leading zeros.
  Number(&'t [u8]),
  Digit(u8),
  Letter(u32),
}

/// A collation element: its primary, secondary and tertiary weights.
type Element<'t> = (Primary<'t>, u32, u8);

fn mark(rank: u32) -> Option<u32> {
  (rank != 0).then_some(rank)
}

fn secondary(mark: u32) -> u32 {
  let rank =
    |mark: u32| MARKS.iter().position(|it| *it == mark).map_or(0x1000 + mark, |at| at as u32 + 1);
  match mark >> 16 {
    0 => rank(mark) << 16,
    first => rank(first) << 16 | rank(mark & 0xFFFF),
  }
}

/// The weight of `$`, the first currency sign. Other symbols come right before it.
const DOLLAR: u32 = 279;

/// A lowercase letter's primary weight: ASCII's first, then `þ`, then the others by code point, and Han last.
fn letter(base: u32) -> Primary<'static> {
  Primary::Letter(match base {
    0..0x80 => base,
    0x3400..=0x4DBF | 0x4E00..=0x9FFF | 0x20000.. => 0x1000000 + base,
    _ => 0x100 + base,
  })
}

/// The elements of `char`: none for an ignored character, one, or two for a ligature.
fn of_char(char: char) -> [Option<Element<'static>>; 2] {
  let code = char as u32;
  let one = |element| [Some(element), None];
  match char {
    'a'..='z' => one((letter(code), 0, 0)),
    'A'..='Z' => one((letter(code + 32), 0, 1)),
    '0'..='9' => one((Primary::Digit(code as u8), 0, 0)),
    'æ' | 'Æ' | 'œ' | 'Œ' | 'ß' | 'ẞ' => {
      let case = 2 + u8::from(char.is_uppercase());
      let (first, second, mark) = match char {
        'æ' | 'Æ' => ('a', 'e', 0xFFF0),
        'œ' | 'Œ' => ('o', 'e', 0xFFF0),
        _ => ('s', 's', 0xFFF1),
      };
      [Some((letter(first as u32), mark << 16, case)), Some((letter(second as u32), 0, case))]
    }
    'þ' | 'Þ' => one((Primary::Letter(0x7B), 0, u8::from(char == 'Þ'))),
    _ => {
      if let Ok(at) = SYMBOLS.binary_search_by_key(&code, |it| it.0) {
        return one((Primary::Symbol(u32::from(SYMBOLS[at].1) << 21), 0, 0));
      }
      if let Ok(at) = LETTERS.binary_search_by_key(&code, |it| it.0) {
        let (_, base, mark, upper) = LETTERS[at];
        return one((letter(base), secondary(mark), u8::from(upper)));
      }
      if char.is_control() || char == '\u{AD}' {
        return [None, None];
      }
      if !char.is_alphanumeric() {
        return one((Primary::Symbol((DOLLAR << 21) - (1 << 20) + code.min(0xFFFFF)), 0, 0));
      }
      let lower = char.to_lowercase().next().unwrap_or(char);
      one((letter(lower as u32), 0, u8::from(lower != char)))
    }
  }
}

fn elements(text: &[u8], numeric: bool) -> impl Iterator<Item = Element<'_>> {
  let text = std::str::from_utf8(text).unwrap_or_default();
  let mut rest = text;
  let mut pending: Option<Element<'_>> = None;
  std::iter::from_fn(move || {
    if let Some(element) = pending.take() {
      return Some(element);
    }
    loop {
      let char = rest.chars().next()?;
      if numeric && char.is_ascii_digit() {
        let len = rest.bytes().take_while(u8::is_ascii_digit).count();
        let digits = rest[..len].trim_start_matches('0').as_bytes();
        rest = &rest[len..];
        return Some((Primary::Number(digits), 0, 0));
      }
      rest = &rest[char.len_utf8()..];
      if let [Some(first), second] = of_char(char) {
        pending = second;
        return Some(first);
      }
    }
  })
}

impl Primary<'_> {
  fn compare(self, other: Self) -> Ordering {
    match (self, other) {
      (Primary::Number(a), Primary::Number(b)) => a.len().cmp(&b.len()).then_with(|| a.cmp(b)),
      _ => self.cmp(&other),
    }
  }
}

fn collate(a: &[u8], b: &[u8], is_numeric_and_base: bool) -> Ordering {
  let (mut left, mut right) = (elements(a, is_numeric_and_base), elements(b, is_numeric_and_base));
  let order = loop {
    match (left.next(), right.next()) {
      (None, None) => break Ordering::Equal,
      (None, Some(_)) => break Ordering::Less,
      (Some(_), None) => break Ordering::Greater,
      (Some(a), Some(b)) => match a.0.compare(b.0) {
        Ordering::Equal => {}
        order => break order,
      },
    }
  };
  if order != Ordering::Equal || is_numeric_and_base {
    return order;
  }
  let marks = |text| {
    let marks =
      elements(text, false).flat_map(|it| [Some(0), mark(it.1 >> 16), mark(it.1 & 0xFFFF)]);
    marks.flatten().collect::<Vec<u32>>()
  };
  let cases = |text| elements(text, false).map(|it| it.2).collect::<Vec<u8>>();
  marks(a).cmp(&marks(b)).then_with(|| cases(a).cmp(&cases(b)))
}

/// `a.localeCompare(b, "en")`
pub(super) fn locale_compare(a: &[u8], b: &[u8]) -> Ordering {
  collate(a, b, false)
}

/// `new Intl.Collator("en", { numeric: true, sensitivity: "base" }).compare(a, b)`: without regard to case and
/// accents, and a run of digits counts as the number that it is.
pub(super) fn locale_compare_numeric_base(a: &[u8], b: &[u8]) -> Ordering {
  collate(a, b, true)
}
