//! Prettier's languages, for `inferParser(options, { language })`. Generated from Prettier 3.9.9's `getSupportInfo()`.

struct Language {
  name: &'static str,
  aliases: &'static [&'static str],
  extensions: &'static [&'static str],
  parser: &'static str,
}

/// `inferParser(options, { language })`: the parser of the language with this name, alias, or extension.
pub(crate) fn parser(language: &str) -> Option<&'static str> {
  let extension =
    |it: &&Language| it.extensions.iter().any(|ext| ext.strip_prefix('.') == Some(language));
  LANGUAGES
    .iter()
    .find(|it| it.name == language)
    .or_else(|| LANGUAGES.iter().find(|it| it.aliases.contains(&language)))
    .or_else(|| LANGUAGES.iter().find(extension))
    .map(|it| it.parser)
}

